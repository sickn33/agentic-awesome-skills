def e(s):
    return html.escape(str(s))


def plural(n, forms, lang):
    n = abs(int(round(n)))
    if lang == 'en':
        return forms[0] if n == 1 else forms[1]
    if n % 10 == 1 and n % 100 != 11:
        return forms[0]
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return forms[1]
    return forms[2]


def fmt_int(x, lang):
    s = f'{x:,.0f}'
    return s if lang == 'en' else s.replace(',', ' ')


def fmt_money(x, ccy, lang):
    sym = SYMBOL.get(ccy, ccy)
    if lang == 'en':
        return f'{sym}{x:,.0f}' if sym in SYMBOL.values() else f'{x:,.0f} {sym}'
    return f'{fmt_int(x, lang)} {sym}'


def fmt_pct(x):
    return f'{x * 100:.0f}%'


def fmt_dec(x, lang):
    s = f'{x:.1f}'
    return s if lang == 'en' else s.replace('.', ',')


def fmt_metric(key, v, ccy, lang):
    if key in PCT:
        return fmt_pct(v)
    if key in MONEY:
        return fmt_money(v, ccy, lang)
    if key in RATIO:
        return fmt_dec(v, lang) + 'x'
    if key in HOURS:
        return f"{v:.0f} {LANGS[lang]['hours_unit']}"
    return fmt_int(v, lang)


def fmt_hours(h, lang):
    """Часы: до 72 часов в часах, дальше в днях (168 ч = 7 дней)."""
    tr = LANGS[lang]
    if h >= 72 and h % 24 == 0:
        d = int(h // 24)
        return f'{d} {plural(d, tr["days_unit"], lang)}'
    return f'{h:g} {tr["hours_unit"]}'


def type_list(types, banned, lang):
    names = LANGS[lang]['mtype']
    return ', '.join(names['debit_card'] if t == 'card' and 'credit_card' in banned else names.get(t, t) for t in types)


def limit_items(limits, lang):
    """Тексты законных лимитов страны: обязательные лимиты, блок по чистым депозитам, суммы по периодам."""
    tr = LANGS[lang]
    gn, out, caps = tr['gn'], [], {}
    eur = lambda v: fmt_money(v, 'EUR', lang)
    for lim in limits:
        kind = lim.get('kind')
        if kind == 'mandatory':
            out.append(gn['mandatory'])
        elif kind == 'net_block':
            out.append(gn['net_block'].format(v=eur(lim['eur']), young=eur(lim.get('young_eur', lim['eur']))))
        elif kind == 'cap':
            caps.setdefault((lim.get('scope'), lim.get('from'), tuple(lim.get('types') or ())), []).append(lim)
    for (scope, since, types), group in caps.items():
        v = ', '.join(gn['cap_per'].format(v=eur(x['eur']), period=tr['period'][x.get('period', 'month')]) for x in group)
        out.append(gn['cap'].format(v=v, scope=gn['cap_all'] if scope == 'all_operators' else '',
                                    types=gn['cap_types'].format(types=type_list(types, [], lang)) if types else '',
                                    since=gn['cap_since'].format(d=fmt_date(since, lang)) if since else ''))
    return out


def geo_items(notes, lang):
    """Правила страны из заметок расчета (sd_analyze.geo_notes) текстами без кода страны."""
    gn, out = LANGS[lang]['gn'], []
    for kind, p in notes or ():
        if kind == 'allowed':
            out.append(gn['allowed'].format(types=type_list(p['types'], p.get('banned', []), lang)))
        elif kind == 'banned':
            out.append(gn['banned'].format(types=type_list(p['types'], [], lang)))
        elif kind in ('own_name', 'single_method', 'bank_blocks'):
            out.append(gn[kind])
        elif kind == 'limits':
            out += limit_items(p['limits'], lang)
        elif kind == 'payout':
            out.append(gn['payout_over' if p.get('over') else 'payout'].format(h=fmt_hours(p['h'], lang)))
        elif kind == 'withdraw':
            out.append(gn['withdraw'].format(n=p.get('per_day'), w=fmt_pct(p.get('wager_share', 0))))
    return out


def geo_note_text(notes, lang):
    """Колонка country_rules списка: код страны один раз и правила через точку с запятой."""
    items = geo_items(notes, lang)
    return f"{notes[0][1].get('c', '')}: " + '; '.join(items) if items else ''


def country_notes(row, payout=True):
    """Все правила страны строки summary.geo_rules.countries в виде заметок для geo_items."""
    c, notes = row['code'], []
    if payout and row.get('payout_hours'):
        notes.append(('payout', {'c': c, 'h': row['payout_hours']}))
    if row.get('allowed'):
        notes.append(('allowed', {'c': c, 'types': row['allowed'], 'banned': row.get('banned', [])}))
    elif row.get('banned'):
        notes.append(('banned', {'c': c, 'types': row['banned']}))
    for key in ('own_name', 'single_method'):
        if row.get(key):
            notes.append((key, {'c': c}))
    if row.get('limits'):
        notes.append(('limits', {'c': c, 'limits': row['limits']}))
    if row.get('bank_blocks'):
        notes.append(('bank_blocks', {'c': c}))
    if row.get('withdraw_conditions'):
        notes.append(('withdraw', dict(row['withdraw_conditions'], c=c)))
    return notes


