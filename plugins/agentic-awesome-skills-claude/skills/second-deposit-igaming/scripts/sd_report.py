    out.append(f'<div class="kicker">{e(tr["title"])}{demo}</div><h1>{e(tr["h1"])}</h1><p class="cav">{e(tr["review_notice"])}</p>')
    sub = tr['sub'].format(cfrom=fmt_date(s['cohort_from'], lang), cto=fmt_date(s['cohort_to'], lang), as_of=fmt_date(s['as_of'], lang),
                           std=std, h=f"{p['rescue_hours']:g}")
    out.append(f'<p class="sub">{e(sub)}</p>')
    k = tr['kpi']
    out.append('<section class="kpis">'
               f'<div class="kpi"><b>{fmt_int(ov["ftd"], lang)}</b><span>{e(k[0])}</span></div>'
               f'<div class="kpi"><b>{fmt_pct(ov["std_rate"])}</b><span>{e(k[1].format(std=std))}</span></div>'
               f'<div class="kpi"><b>{fmt_pct(ov["norm_rate"])}</b><span>{e(k[2])}</span></div>'
               f'<div class="kpi accent"><b>{e(tr["upto"].format(v=fmt_money(ov["lost_month"], ccy, lang)))}</b><span>{e(k[3])}</span>'
               f'<span class="min">{e(tr["kpi_min"].format(v=fmt_money(ov.get("lost_month_min", 0), ccy, lang)))}</span></div></section>')
    # причины
    out.append(f'<section class="card"><h2>{e(tr["sc_title"])}</h2><p class="hint">{e((tr["sc_hint"].format(value=value) + " " + ready_text(s, tr)).strip())}</p>'
               '<table><thead><tr>')
    out += [f'<th>{e(h)}</th>' for h in tr['sc_th']]
    out.append('</tr></thead><tbody>')
    rows = sorted([x for x in s['scenarios'] if x['key'] != 'other'], key=lambda x: (not x['available'], -x['lost_month'], -x['n'])) + \
        [x for x in s['scenarios'] if x['key'] == 'other']
    for x in rows:
        name, desc = tr['sc'][x['key']]
        desc = desc.format(**fill)
        stat = stat_line(x, tr, lang) if x['available'] else ''
        cls = 'off' if not x['available'] else 'base' if x['key'] == 'other' else ''
        out.append(f'<tr class="{cls}"><td class="name"><b>{e(name)}</b><small>{e(desc)}</small>' + (f'<small>{e(stat)}</small>' if stat else '') + '</td>')
        if not x['available']:
            out.append(f'<td class="num">-</td><td>{e(tr["no_data"])}</td><td class="lost zero"><b>-</b></td><td class="act">{e(tr["act"][x["key"]])}</td></tr>')
            continue
        out.append(f'<td class="num">{fmt_int(x["n"], lang)}<small>{fmt_pct(x["share"])}</small></td>')
        rate_txt = f'{fmt_pct(x["rate"])} · {tr["is_norm"]}' if x['key'] == 'other' else \
            tr['rate_vs'].format(rate=fmt_pct(x['rate']), norm=fmt_pct(x['expected_rate']))
        out.append(f'<td><div class="bar"><i style="width:{min(100, x["rate"] * 100):.1f}%"></i>'
                   f'<u style="left:{min(100, x["expected_rate"] * 100):.1f}%"></u></div><small>{e(rate_txt)}</small></td>')
        if x['key'] == 'other' or x['lost_month'] < 1:
            out.append('<td class="lost zero"><b>0</b></td>')
        else:
            gp = x['gap_players_month']
            noise = f'<small>{e(tr["noise"])}</small>' if x.get('z', 9) < 2 else ''
            out.append(f'<td class="lost"><b>{e(tr["upto"].format(v=fmt_money(x["lost_month"], ccy, lang)))}</b>'
                       f'<small>{e(tr["from"].format(v=fmt_money(x.get("lost_month_min", 0), ccy, lang)))}</small>'
                       f'<small>{fmt_int(gp, lang)} {e(plural(gp, tr["deps"], lang))}</small>{noise}</td>')
        out.append(f'<td class="act">{e(tr["act"][x["key"]])}</td></tr>')
    out.append('</tbody></table></section>')
    # показатели и динамика
    mt = s.get('metrics') or {}
    if mt:
        out.append(f'<section class="card"><h2>{e(tr["metrics_title"])}</h2><p class="hint">{e(tr["metrics_hint"])}</p><div class="mgrid">')
        for gkey, keys in METRIC_GROUPS:
            items = [kk for kk in keys if kk in mt]
            if not items:
                continue
            out.append(f'<div><h3>{e(tr["groups"][gkey])}</h3>')
            for kk in items:
                label, definition = tr['metric'][kk]
                out.append(f'<div class="metric"><span>{e(label)}</span><b>{e(fmt_metric(kk, mt[kk], ccy, lang))}</b>'
                           f'<small>{e(definition.format(**fill))}</small></div>')
            out.append('</div>')
        out.append('</div>')
        wk = s.get('weekly') or []
        if wk:
            top = max(w['rate'] for w in wk) or 1
            out.append(f'<h3 style="margin-top:22px">{e(tr["weekly_title"])}</h3><p class="hint" style="margin:0">{e(tr["weekly_hint"])}</p><div class="weeks">')
            for w in wk:
                out.append(f'<div class="week"><small>{e(fmt_date(w["week"], lang)[:5] if lang != "en" else w["week"][5:])}</small>'
                           f'<i style="width:{w["rate"] / top * 100:.0f}%"></i><b>{fmt_pct(w["rate"])}</b><small>FTD {fmt_int(w["n"], lang)}</small></div>')
            out.append('</div>')
        out.append('</section>')
    out.append(profile_block(s, tr, lang, table=False))
    out.append(geo_block(s, tr, lang))
    # срезы
    if s['segments']:
        out.append(f'<section class="card"><h2>{e(tr["seg_title"])}</h2><p class="hint">{e(tr["seg_hint"])}</p><table><thead><tr>')
        out += [f'<th>{e(h)}</th>' for h in tr['seg_th']]
        out.append('</tr></thead><tbody>')
        for x in s['segments']:
            out.append(f'<tr><td class="name"><b>{e(group_label(x, s, tr))}</b><small>{e(tr["dim"][x["dim"]])}</small></td>'
                       f'<td class="num">{fmt_int(x["n"], lang)}</td><td class="num">{fmt_pct(x["rate"])}</td>'
                       f'<td class="num">{fmt_pct(x["expected_rate"])}</td><td class="lost"><b>{e(tr["upto"].format(v=fmt_money(x["lost_month"], ccy, lang)))}</b>'
                       f'<small>{e(tr["from"].format(v=fmt_money(x.get("lost_month_min", 0), ccy, lang)))}</small></td></tr>')
        out.append('</tbody></table></section>')
    # список на сегодня
    r = s['rescue']
    out.append(f'<section class="card"><h2>{e(tr["rescue_title"])}</h2>')
    if r['total']:
        who = f'{fmt_int(r["total"], lang)} {plural(r["total"], tr["players"], lang)}'
        text = tr['rescue_text'].format(n=who, h=f"{p['rescue_hours']:g}")
        order = [x['key'] for x in s['scenarios']]
        chips = ''.join(f'<span class="chip{" warn" if a == "persist" else ""}">{e(tr["sc"][a][0])}: <b>{fmt_int(n, lang)}</b></span>'
                        for a, n in sorted(r['by_scenario'].items(), key=lambda kv: order.index(kv[0])))
        notes = [tr['rescue_snap'].format(t=fmt_date(r.get('snapshot', s['as_of']), lang), n=fmt_int(r.get('ftd_in_window', 0), lang),
                                          k=fmt_int(r.get('with_second_deposit', 0), lang), h=f"{p['rescue_hours']:g}")]
        if r['excluded_rg']:
            notes.append(tr['rescue_rg'].format(n=r['excluded_rg']))
        if r.get('control'):
            notes.append(tr['control_note'].format(n=fmt_int(r['control'], lang), share=fmt_pct(p.get('control_share', 0))))
        fcn = forecast_note(s, tr, lang)
        if fcn:
            notes.insert(0, fcn)
        out.append(f'<div class="rescue"><div class="big">{fmt_int(r["total"], lang)}</div><div><p>{e(text)}</p>'
                   + ''.join(f'<p class="hint" style="margin:6px 0 0">{e(n)}</p>' for n in notes)
                   + f'<div class="chips">{chips}</div></div></div>')
    else:
        out.append(f'<p class="hint">{e(tr["rescue_empty"])}</p>')
    out.append('</section>')
    out.append(effect_block(s, tr, lang, std))
    rule = tr['rule'][s['ftd_rule']].format(warmup='30')
    items = [t.format(rule=rule, std=std, value=value) for t in tr['how']]
    out.append(f'<section class="card how"><h2>{e(tr["how_title"])}</h2><ul style="margin-top:10px">' + ''.join(f'<li>{e(t)}</li>' for t in items) + '</ul>')
    cav = [tr['cav'][c].format(value_full='30', std=std) for c in s['caveats'] if tr['cav'].get(c)]
    seen = set()
    cav = [c for c in cav if not (c in seen or seen.add(c))]
    if cav:
        out.append('<div class="cav">' + '<br>'.join(e(c) for c in cav) + '</div>')
    out.append(f'</section><p class="foot">{e(tr["foot"])} Yevhen Sychov · sychov-igaming.com</p></main></body></html>')
    return ''.join(out)
