    parts = [tr['geo_ap'][k].format(n=fmt_int(a[k], lang)) for k in tr['geo_ap'] if a.get(k)]
    if parts:
        notes.append(tr['geo_applied'].format(v='; '.join(parts)))
    if g.get('banned_in_data'):
        notes.append(tr['geo_banned_data'].format(v='; '.join(
            f"{c}: " + ', '.join(f"{tr['mtype'].get(t, t)} {fmt_int(n, lang)}" for t, n in v.items()) for c, v in g['banned_in_data'].items())))
