def band_text(b, summary, tr):
    ccy, lang = summary['currency'], summary['lang']
    lo, hi = b['lo'], b['hi']
    if lo is None and hi is None:
        return '-'
    if lo is None:
        return tr['band_lo'].format(hi=fmt_money(hi, ccy, lang))
    if hi is None:
        return tr['band_hi'].format(lo=fmt_money(lo, ccy, lang))
    return tr['band_mid'].format(lo=fmt_money(lo, ccy, lang), hi=fmt_money(hi, ccy, lang))


def group_label(x, summary, tr):
    g = x['group']
    if x['dim'] == 'band':
        return band_text(summary['bands'][g], summary, tr)
    if x['dim'] == 'hour':
        return f'{g * 6:02d}-{g * 6 + 6:02d}'
    if x['dim'] == 'bonus':
        return tr['bonus_g'][g]
    return str(g)


def stat_line(x, tr, lang):
    st, parts = x['stats'], []
    for key in ('turnover_x', 'bet_share', 'session_min', 'methods', 'limit_share', 'withdrawal_x', 'withdraw_hours', 'win_x', 'bonuses'):
        if key not in st or st[key] is None:
            continue
        v = st[key]
        if key in ('turnover_x', 'withdrawal_x', 'win_x'):
            v = fmt_dec(v, lang)
        elif key in ('bet_share', 'limit_share'):
            v = fmt_pct(v)
        elif key in ('session_min', 'withdraw_hours'):
            v = f'{v:.0f}'
        elif isinstance(v, dict):
            v = ', '.join(k for k in v if k)
            if not v:
                continue
        parts.append(tr['stat'][key].format(v=v))
    return ' · '.join(parts)


