/**
 * Concatenate the Worker sources into one file.
 *
 * Cloudflare's dashboard editor takes a single script, which lets someone
 * deploy by pasting - no API token, no terminal, no local checkout. Building
 * it from the same sources the tests run against keeps the two from drifting.
 */

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "src");
const outPath = join(here, "..", "dist", "worker.js");

// Dependency order: naver.js defines what tools.js uses, and so on.
const FILES = ["naver.js", "tools.js", "index.js"];

const RELATIVE_IMPORT = /^import\s*\{[\s\S]*?\}\s*from\s*["']\.\/[^"']+["'];?\s*$/gm;

const strip = (code) =>
  code
    .replace(RELATIVE_IMPORT, "")
    // `export default` must survive - it is the Worker entrypoint.
    .replace(/^export (?!default)/gm, "")
    .trim();

const parts = [];
for (const name of FILES) {
  const code = await readFile(join(src, name), "utf8");
  parts.push(`// ${"=".repeat(70)}\n// ${name}\n// ${"=".repeat(70)}\n\n${strip(code)}`);
}

const banner = `// Naver Content MCP - single-file Cloudflare Worker build.
// Generated by scripts/bundle.mjs from src/*.js - edit those, not this.
// Paste into the Cloudflare dashboard editor (Workers > Create > Edit code).
`;

await mkdir(dirname(outPath), { recursive: true });
await writeFile(outPath, `${banner}\n${parts.join("\n\n")}\n`, "utf8");

const bytes = (await readFile(outPath, "utf8")).length;
console.log(`wrote ${outPath} (${bytes} bytes)`);
